// Generates src/plugin/plugin.js, the script the SDK bundles for the
// app's plugin: src/pkjs/trips.js wrapped as a `trips` object, then
// src/plugin/main.js. The SDK copies a plugin script as is (no require()),
// and this keeps the SIRI parsing and call guard in one place.
// `--check` only verifies the committed file is up to date (exit 1 if not).
const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");
const read = (file) =>
	fs.readFileSync(path.join(root, file), "utf8").replace(/\r\n/g, "\n");
const out = path.join(root, "src", "plugin", "plugin.js");

const generated = `// GENERATED by scripts/build-plugin.js from src/pkjs/trips.js and
// src/plugin/main.js -- edit those, then run \`npm run sync:plugin\`.

const trips = (() => {
	const module = { exports: {} };
${read("src/pkjs/trips.js")
	.trim()
	.split("\n")
	.map((line) => (line ? `\t${line}` : line))
	.join("\n")}
	return module.exports;
})();

${read("src/plugin/main.js").trim()}
`;

const current = fs.existsSync(out) ? read("src/plugin/plugin.js") : "";
if (process.argv.includes("--check")) {
	if (current !== generated) {
		console.error("src/plugin/plugin.js is out of date -- run npm run sync:plugin");
		process.exit(1);
	}
	console.log("plugin.js in sync");
} else {
	fs.writeFileSync(out, generated);
	console.log(current === generated ? "plugin.js already in sync" : "plugin.js updated");
}
